#!/usr/bin/env python3
"""Validate native language resources; regenerate identity English strings when requested."""
import argparse
import collections
import json
from pathlib import Path
import plistlib
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
RESOURCES = ROOT / "Packages/NimbusSyncDomainKit/Sources/Resources"


def load_strings(path):
    raw = path.read_text()
    keys = re.findall(r'^"((?:[^"\\]|\\.)*)"\s*=', raw, flags=re.MULTILINE)
    duplicates = [key for key, count in collections.Counter(keys).items() if count > 1]
    if duplicates:
        raise ValueError(f"Duplicate keys in {path}: {duplicates}")
    return json.loads(subprocess.check_output(["plutil", "-convert", "json", "-o", "-", str(path)]))


def placeholders(text):
    # Positional translations may reorder arguments; normalize only the position annotation.
    return sorted(re.sub(r'^%\d+\$', '%', match) for match in
                  re.findall(r'%(?:\d+\$)?(?:lld|llu|ld|lu|lf|f|d|u|@)', text.replace('%%', '')))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--generate-english", action="store_true")
    parser.add_argument("--build-root", type=Path, help="Check compiler-extracted stringsdata under an Xcode build root")
    args = parser.parse_args()
    chinese = load_strings(RESOURCES / "zh-Hans.lproj/Localizable.strings")
    english_path = RESOURCES / "en.lproj/Localizable.strings"
    if args.generate_english:
        quote = lambda value: json.dumps(value, ensure_ascii=False)
        english_path.write_text("/* Generated by Scripts/check-localization.py --generate-english. */\n" +
                                "".join(f"{quote(key)} = {quote(chinese[key] if key.startswith('finder.action.') else key)};\n" for key in sorted(chinese)))
    english = load_strings(english_path)
    assert english.keys() == chinese.keys(), "English and Chinese string keys differ"
    for key, translated in chinese.items():
        assert translated.strip(), f"Empty translation: {key}"
        assert placeholders(key) == placeholders(translated), f"Argument mismatch: {key}"
    plurals = {}
    for language in ["en", "zh-Hans"]:
        with (RESOURCES / f"{language}.lproj/Localizable.stringsdict").open("rb") as stream:
            plurals[language] = plistlib.load(stream)
        for key, value in plurals[language].items():
            assert "NSStringLocalizedFormatKey" in value, f"Missing plural format: {key}"
            for argument, rule in value.items():
                if isinstance(rule, dict):
                    assert "other" in rule, f"Missing plural fallback: {language}/{key}/{argument}"
    assert plurals["en"].keys() == plurals["zh-Hans"].keys(), "Plural keys differ"
    if args.build_root:
        known = set(english) | set(plurals["en"])
        # User-independent branding, URL placeholders and numeric-only UI are intentionally stable.
        invariant = {"%lld", "cloud.example.com", "Cloudreve %@", "Apache License 2.0", "github.com/jorben/NimbusSync"}
        missing = {}
        checked = 0
        for path in args.build_root.glob("**/Objects-normal/*/*.stringsdata"):
            if "/SourcePackages/" in str(path):
                continue
            data = json.loads(path.read_text())
            source = data.get("source", "")
            if not source.startswith(str(ROOT)):
                continue
            checked += 1
            for entries in data.get("tables", {}).values():
                for entry in entries:
                    key = entry["key"]
                    if key.strip() and any(c.isalpha() for c in key) and key not in known | invariant:
                        missing[key] = source
        assert checked, "No compiler-extracted localization records found"
        assert not missing, "Missing compiler-extracted keys: " + repr(missing)
        print(f"Checked native localization extraction from {checked} Swift compilation records.")
    print(f"Validated {len(english)} strings and {len(plurals['en'])} plural entries in both languages.")


if __name__ == "__main__":
    main()
